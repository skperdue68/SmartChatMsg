test("schedule configuration survives reload and additive V1 export/import", function()
    assert(scm:SaveGuildSchedule("ad", "Amber Traders", draft()))
    scm:GetGuildSchedule("ad", "Amber Traders").paused=true
    ZO_SavedVars={NewAccountWide=function() return scm.savedVars end}
    scm:InitializeSavedVars()
    eq(scm:GetGuildSchedule("ad", "Amber Traders").paused,true)
    local exported=scm:BuildExportString()
    local ok, reason=scm:ImportSettingsFromString(exported)
    assert(ok,reason)
    local s=scm:GetGuildSchedule("ad", "Amber Traders")
    eq(s.paused,true); eq(s.messagePhases.b.DAY,true); eq(s.phaseIntervals.DAY,15)
    eq(s.startsAtUtc,1792080000)
end)
local function savedRuntime()
    assert(scm:SaveGuildSchedule("ad","Amber Traders",draft()))
    now=1792080000
end
local function sent()
    local text=CHAT_SYSTEM.textEntry.EditControl.text
    CHAT_SYSTEM.textEntry.EditControl.text=""
    scm:HandleRestoreWatcherChatMessage(2,3,"My Character",text,false,"@Me")
end
test("scheduler activates inside the window and stops at its end", function()
    savedRuntime(); scm:TickSchedules()
    assert(CHAT_SYSTEM.textEntry.EditControl.text:find("Friday"))
    assert(scm.pendingRestoreState.metadata.scheduledDelivery)
    now=1792198800; scm:TickSchedules()
