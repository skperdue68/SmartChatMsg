    savedRuntime(); scm:TickSchedules(); sent()
    eq(scm:GetGuildSchedule("ad","Amber Traders").nextDueAt,1792080300)
    now=1792080299; scm:TickSchedules(); eq(CHAT_SYSTEM.textEntry.EditControl.text,"")
