test("incoming event tokens retain event identity while eventwhen and countdown vary", function()
    savedRuntime()
    local entry=scm.savedVars.messages[1]
    entry.text="%guild% trial %eventwhen%, %eventdate% at %eventtime%."
    local function matches(text) return scm:MatchesIncomingMessage(entry,"Amber Traders",scm:NormalizeIncomingChatText(text)) end
    assert(matches("Amber Traders trial tomorrow, 10/16/2026 at 08:00 PM EDT (about 2h)."))
    assert(not matches("Amber Traders trial today, 10/16/2026 at 08:00 PM EDT (about 2h)."))
    now=1792123200
    assert(matches("Amber Traders trial today, 10/16/2026 at 08:00 PM EDT (about 2h)."))
    assert(not matches("Amber Traders trial today, 10/17/2026 at 08:00 PM EDT (about 2h)."))
    assert(not matches("Amber Traders trial whenever, 10/16/2026 at 08:00 PM EDT (about 2h)."))
    local d=draft(); d.eventTime="07:00 PM"; assert(scm:SaveGuildSchedule("ad","Amber Traders",d))
    assert(not matches("Amber Traders trial today, 10/16/2026 at 08:00 PM EDT (about 2h)."))
end)
