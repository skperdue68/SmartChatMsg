local f = dofile("tests/eso_fixture.lua")
local scm, eq = f.scm, f.eq
local tests = {}
local function test(name, fn) tests[#tests + 1] = {name, fn} end
local function draft()
    return { enabled=true, startDate="2026-10-15", startTime="12:00 PM", eventDate="2026-10-16", eventTime="08:00 PM",
        endDate="2026-10-16", endTime="09:00 PM", delivery="REPEAT", intervalMinutes=5,
        messagePhases={a={BEFORE=true}, b={DAY=true}, c={LIVE=true}}, phaseIntervals={DAY=15} }
end
local function setup()
    f.reset()
    scm.scheduleRuntime, scm.chatPopulationQueue = {}, {}
    f.entry("a", "ad", "Amber Traders", "Amber Traders trial Friday at 8 PM EDT.")
    f.entry("b", "ad", "Amber Traders", "Amber Traders trial tonight at 8 PM EDT.")
    f.entry("c", "ad", "Amber Traders", "Amber Traders trial is underway.")
    assert(type(scm.SaveGuildSchedule) == "function", "schedule configuration is missing")
end
test("validated Save stores the expected Eastern instants and enables Scheduled mode", function()
    local ok, reason = scm:SaveGuildSchedule("ad", "Amber Traders", draft())
    assert(ok, reason)
    local s = scm:GetGuildSchedule("ad", "Amber Traders")
    eq(s.startsAtUtc,1792080000); eq(s.eventAtUtc,1792195200); eq(s.endsAtUtc,1792198800)
    eq(scm:GetGuildRunAt("ad", "Amber Traders"), "SCHEDULED")
end)
test("invalid Save is transactional and keeps the previous schedule", function()
    assert(scm:SaveGuildSchedule("ad", "Amber Traders", draft()))
    local previous = scm:GetGuildSchedule("ad", "Amber Traders")
    local invalid = draft(); invalid.endTime="07:00 PM"
    local ok, reason = scm:SaveGuildSchedule("ad", "Amber Traders", invalid)
    eq(ok,false); assert(reason); eq(scm:GetGuildSchedule("ad", "Amber Traders"),previous)
end)
test("window starts inclusively and finishes exclusively even if paused", function()
    assert(scm:SaveGuildSchedule("ad", "Amber Traders", draft()))
    eq(scm:GetGuildScheduleState("ad", "Amber Traders",1792079999),"WAITING")
    eq(scm:GetGuildScheduleState("ad", "Amber Traders",1792080000),"RUNNING")
    eq(scm:GetGuildScheduleState("ad", "Amber Traders",1792198800),"FINISHED")
    scm:GetGuildSchedule("ad", "Amber Traders").paused=true
    eq(scm:GetGuildScheduleState("ad", "Amber Traders",1792198799),"PAUSED")
    eq(scm:GetGuildScheduleState("ad", "Amber Traders",1792198800),"FINISHED")
end)
