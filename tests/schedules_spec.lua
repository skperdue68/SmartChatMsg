test("peer usage while paused advances the due time without resuming", function()
    savedRuntime(); scm:TickSchedules(); sent(); scm:PauseGuildSchedule("ad","Amber Traders")
    now=now+100; f.incoming(CHAT_CHANNEL_ZONE,"Amber Traders trial Friday at 8 PM EDT.")
